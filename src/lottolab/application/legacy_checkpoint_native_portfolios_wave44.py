class LegacyCheckpointNativeWave44Error(ValueError):
    """The request or packaged ticket ledger violates the wave-44 contract."""


class LegacyCheckpointNativeWave44SourceError(
    LegacyCheckpointNativeWave44Error
):
    """A target cannot safely consume a frozen checkpoint ticket."""

    def __init__(self, reason_code: str) -> None:
        super().__init__(reason_code)
        self.reason_code = reason_code


