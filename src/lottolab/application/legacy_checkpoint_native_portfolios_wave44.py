@dataclass(frozen=True, slots=True)
class LegacyCheckpointNativeWave44Result:
    tickets: tuple[Ticket, ...]
    metadata: LegacyCheckpointNativeWave44Metadata


@dataclass(frozen=True, slots=True)
class _Ledger:
    targets: tuple[str, ...]
    context_sha256: tuple[str, ...]
    tickets_by_method: MappingProxyType[str, tuple[Ticket, ...]]


def _canonical_bytes(value: object) -> bytes:
    return json.dumps(
        value,
        ensure_ascii=False,
        separators=(",", ":"),
        sort_keys=True,
    ).encode("utf-8")


def _ticket(value: object) -> Ticket:
    if not isinstance(value, list):
        raise LegacyCheckpointNativeWave44Error(
            "packaged wave-44 ticket must be an array"
        )
    values = cast(list[object], value)
    integer_values = (
        cast(list[int], values)
        if all(type(number) is int for number in values)
        else []
    )
    if (
        len(values) != 6
        or len(integer_values) != 6
        or len(set(values)) != 6
        or integer_values != sorted(integer_values)
        or any(not 1 <= cast(int, number) <= 49 for number in values)
    ):
        raise LegacyCheckpointNativeWave44Error(
            "packaged wave-44 ticket is not a sorted legal ticket"
        )
    return cast(Ticket, tuple(integer_values))


@lru_cache(maxsize=1)
def _load_ledger() -> _Ledger:
    resource = files("lottolab.strategies.data").joinpath(
        LEDGER_RESOURCE_NAME
    )
    raw = resource.read_bytes()
    if hashlib.sha256(raw).hexdigest() != LEDGER_FILE_SHA256:
        raise LegacyCheckpointNativeWave44Error(
            "packaged wave-44 ledger file SHA changed"
        )
    try:
        parsed = json.loads(raw)
    except json.JSONDecodeError as exc:
        raise LegacyCheckpointNativeWave44Error(
            "packaged wave-44 ledger is invalid JSON"
        ) from exc
    if not isinstance(parsed, dict):
        raise LegacyCheckpointNativeWave44Error(
            "packaged wave-44 ledger must be an object"
        )
    document = cast(dict[str, Any], parsed)
    claimed_content_sha256 = document.pop("ledger_content_sha256", None)
    if (
        claimed_content_sha256 != LEDGER_CONTENT_SHA256
        or hashlib.sha256(_canonical_bytes(document)).hexdigest()
        != LEDGER_CONTENT_SHA256
        or document.get("ledger_schema_version")
        != LEDGER_SCHEMA_VERSION
        or document.get("frozen_source_commit") != FROZEN_SOURCE_COMMIT
        or document.get("dataset_sha256") != PINNED_DATASET_SHA256
        or document.get("artifact_introduction_commit")
        != CHECKPOINT_INTRODUCTION_COMMIT
        or document.get("artifact_introduction_time")
        != CHECKPOINT_INTRODUCTION_TIME
        or document.get("causal_eligibility_rule")
        != CAUSAL_ELIGIBILITY_RULE
        or document.get("context_draw_count")
        != MODEL_CONTEXT_DRAW_COUNT
    ):
        raise LegacyCheckpointNativeWave44Error(
            "packaged wave-44 ledger identity changed"
        )
    targets_raw = document.get("target_draw_numbers")
    context_raw = document.get("context_numbers_sha256_by_target")
    tickets_raw = document.get("tickets_by_method")
    if (
        not isinstance(targets_raw, list)
        or not isinstance(context_raw, list)
        or not isinstance(tickets_raw, dict)
    ):
        raise LegacyCheckpointNativeWave44Error(
            "packaged wave-44 ledger layout changed"
        )
    targets_values = cast(list[object], targets_raw)
    context_values = cast(list[object], context_raw)
    if (
        len(targets_values) != 48
        or len(context_values) != 48
        or len(set(targets_values)) != 48
        or any(type(item) is not str or not item for item in targets_values)
        or any(
            type(item) is not str
            or len(item) != 64
            or any(character not in "0123456789abcdef" for character in item)
            for item in context_values
        )
    ):
        raise LegacyCheckpointNativeWave44Error(
            "packaged wave-44 target ledger changed"
        )
    typed_tickets = cast(dict[str, object], tickets_raw)
    if set(typed_tickets) != set(SUPPORTED_SOURCE_NATIVE_WAVE44_METHODS):
        raise LegacyCheckpointNativeWave44Error(
            "packaged wave-44 method set changed"
        )
    by_method: dict[str, tuple[Ticket, ...]] = {}
    for method_id in SUPPORTED_SOURCE_NATIVE_WAVE44_METHODS:
        method_tickets_raw = typed_tickets[method_id]
        if not isinstance(method_tickets_raw, list):
            raise LegacyCheckpointNativeWave44Error(
                "packaged wave-44 method tickets changed"
            )
        method_tickets = tuple(
            _ticket(candidate)
            for candidate in cast(list[object], method_tickets_raw)
        )
        if len(method_tickets) != len(targets_values):
            raise LegacyCheckpointNativeWave44Error(
                "packaged wave-44 method ticket count changed"
            )
        by_method[method_id] = method_tickets
    return _Ledger(
        targets=cast(tuple[str, ...], tuple(targets_values)),
        context_sha256=cast(tuple[str, ...], tuple(context_values)),
        tickets_by_method=MappingProxyType(by_method),
    )


def _validate_request(
    request: LegacyCheckpointNativeWave44Request,
) -> None:
    if (
        request.legacy_method_id
        not in SUPPORTED_SOURCE_NATIVE_WAVE44_METHODS
    ):
        raise LegacyCheckpointNativeWave44Error(
            "legacy method is outside the wave-44 batch"
        )
    if (
        type(request.target_draw_number) is not str
        or not request.target_draw_number
        or type(request.target_draw_date) is not date
        or type(request.replicate_id) is not int
        or request.replicate_id < 0
        or type(request.user_seed) not in (str, int)
        or type(request.dataset_sha256) is not str or not request.dataset_sha256
    ):
        raise LegacyCheckpointNativeWave44Error(
            "invalid frozen checkpoint request identity"
        )
    if request.target_draw_date <= CHECKPOINT_INTRODUCTION_LOCAL_DATE:
        raise LegacyCheckpointNativeWave44SourceError(
            "TARGET_NOT_STRICTLY_AFTER_CHECKPOINT_GIT_INTRODUCTION_LOCAL_DATE"
        )
    if len(request.history) < MODEL_CONTEXT_DRAW_COUNT:
        raise LegacyCheckpointNativeWave44SourceError(
            "AVAILABLE_HISTORY_BELOW_FROZEN_MODEL_CONTEXT"
        )
    seen: set[str] = set()
    for draw in request.history:
        if (
            not draw.draw_number
            or draw.draw_number == request.target_draw_number
            or draw.draw_number in seen
        ):
            raise LegacyCheckpointNativeWave44Error(
                "causal history draw identities are invalid"
            )
        _ticket(list(draw.numbers))
        seen.add(draw.draw_number)


def _context_sha256(
    history: tuple[LegacyHistoryDraw, ...],
) -> str:
    context = [
        list(draw.numbers)
        for draw in history[-MODEL_CONTEXT_DRAW_COUNT:]
    ]
    return hashlib.sha256(
        json.dumps(context, separators=(",", ":")).encode("utf-8")
    ).hexdigest()


def generate_legacy_checkpoint_native_wave44_portfolio(
    request: LegacyCheckpointNativeWave44Request,
) -> LegacyCheckpointNativeWave44Result:
    """Return the exact frozen-runtime ticket for one causal target."""

    _validate_request(request)
    ledger = _load_ledger()
    try:
        target_index = ledger.targets.index(request.target_draw_number)
    except ValueError as exc:
        raise LegacyCheckpointNativeWave44SourceError(
            "TARGET_OUTSIDE_FROZEN_CHECKPOINT_TICKET_LEDGER"
        ) from exc
    context_sha256 = _context_sha256(request.history)
    if context_sha256 != ledger.context_sha256[target_index]:
        raise LegacyCheckpointNativeWave44SourceError(
            "FROZEN_MODEL_CONTEXT_IDENTITY_MISMATCH"
        )
    seed_material = "|".join(
        (
            SOURCE_NATIVE_WAVE44_PROTOCOL,
            request.legacy_method_id,
            SOURCE_SHA256_BY_SOURCE_NATIVE_WAVE44_METHOD[
                request.legacy_method_id
            ],
            request.target_draw_number,
            str(request.replicate_id),
            str(request.user_seed),
        )
    )
    seed_digest = hashlib.sha256(
        seed_material.encode("utf-8")
    ).hexdigest()
    checkpoint_path, checkpoint_sha256, checkpoint_blob_id = (
        CHECKPOINT_BY_SOURCE_NATIVE_WAVE44_METHOD[
            request.legacy_method_id
        ]
    )
    ticket = ledger.tickets_by_method[request.legacy_method_id][
        target_index
    ]
    return LegacyCheckpointNativeWave44Result(
        tickets=(ticket,),
        metadata=LegacyCheckpointNativeWave44Metadata(
            protocol=SOURCE_NATIVE_WAVE44_PROTOCOL,
            legacy_method_id=request.legacy_method_id,
            source_sha256=(
                SOURCE_SHA256_BY_SOURCE_NATIVE_WAVE44_METHOD[
                    request.legacy_method_id
                ]
            ),
            target_draw_number=request.target_draw_number,
            target_draw_date=request.target_draw_date.isoformat(),
            replicate_id=request.replicate_id,
            user_seed=request.user_seed,
            seed_material=seed_material,
            seed_digest=seed_digest,
            seed_integer=int(seed_digest, 16),
            random_protocol=(
                "NONE_FROZEN_CHECKPOINT_MODEL_EVAL_TOP_LOGIT_SELECTION"
            ),
            randomness_used=False,
            randomness_reproduction=(
                "SOURCE_RUNTIME_LEDGER_EXACT_TICKET_REPLAY"
            ),
            history_draw_count=len(request.history),
            history_first_draw_number=request.history[0].draw_number,
            history_cutoff_draw_number=request.history[-1].draw_number,
            source_history_order="OLDEST_FIRST",
            source_history_order_detail=(
                "DATABASE_NEWEST_FIRST_REVERSED_TO_OLDEST_FIRST_THEN_"
                "STRICT_PREFIX_BEFORE_TARGET_AND_LAST15_MODEL_CONTEXT"
            ),
            model_context_draw_count=MODEL_CONTEXT_DRAW_COUNT,
            model_context_numbers_sha256=context_sha256,
            source_candidate_k_values=(MODEL_CANDIDATE_K,),
            candidate_k=None,
            native_ticket_count=1,
            native_ticket_count_semantics=(
                NATIVE_TICKET_SEMANTICS_BY_SOURCE_NATIVE_WAVE44_METHOD[
                    request.legacy_method_id
                ]
            ),
            native_ticket_order="SINGLE_LOCAL_SOURCE_CONFIGURATION_TICKET",
            native_duplicate_ticket_count=0,
            combination_count=None,
            local_source_configuration=(
                LOCAL_SOURCE_CONFIGURATION_BY_SOURCE_NATIVE_WAVE44_METHOD[
                    request.legacy_method_id
                ]
            ),
            imported_comparators_excluded=(
                IMPORTED_COMPARATORS_EXCLUDED_BY_SOURCE_NATIVE_WAVE44_METHOD[
                    request.legacy_method_id
                ]
            ),
            checkpoint_path=checkpoint_path,
            checkpoint_sha256=checkpoint_sha256,
            checkpoint_blob_id=checkpoint_blob_id,
            checkpoint_introduction_commit=(
                CHECKPOINT_INTRODUCTION_COMMIT
            ),
            checkpoint_introduction_time=CHECKPOINT_INTRODUCTION_TIME,
            causal_eligibility_rule=CAUSAL_ELIGIBILITY_RULE,
            source_reference_runtime=SOURCE_REFERENCE_RUNTIME,
            ledger_schema_version=LEDGER_SCHEMA_VERSION,
            ledger_file_sha256=LEDGER_FILE_SHA256,
            ledger_content_sha256=LEDGER_CONTENT_SHA256,
            ledger_target_index=target_index,
            frozen_support_artifacts=(
                FROZEN_SUPPORT_ARTIFACTS_BY_SOURCE_NATIVE_WAVE44_METHOD[
                    request.legacy_method_id
                ]
            ),
        ),
    )


