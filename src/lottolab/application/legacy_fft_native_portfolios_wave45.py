@dataclass(frozen=True, slots=True)
class LegacyFftNativeWave45Result:
    tickets: tuple[Ticket, ...]
    metadata: LegacyFftNativeWave45Metadata


@dataclass(frozen=True, slots=True)
class _Ledger:
    targets: tuple[str, ...]
    context_sha256: tuple[str, ...]
    tickets_by_method: MappingProxyType[str, tuple[tuple[Ticket, ...] | None, ...]]


def _canonical_bytes(value: object) -> bytes:
    return json.dumps(
        value,
        ensure_ascii=False,
        separators=(",", ":"),
        sort_keys=True,
    ).encode("utf-8")


def _ticket(value: object) -> Ticket:
    if not isinstance(value, list):
        raise LegacyFftNativeWave45Error("packaged wave-45 ticket must be an array")
    values = cast(list[object], value)
    integer_values = (
        cast(list[int], values) if all(type(number) is int for number in values) else []
    )
    if (
        len(values) != 6
        or len(integer_values) != 6
        or integer_values != sorted(integer_values)
        or len(set(values)) != 6
        or any(not 1 <= cast(int, number) <= 49 for number in values)
    ):
        raise LegacyFftNativeWave45Error("packaged wave-45 ticket is not a sorted legal ticket")
    return cast(Ticket, tuple(integer_values))


@lru_cache(maxsize=1)
def _load_ledger() -> _Ledger:
    resource = files("lottolab.strategies.data").joinpath(LEDGER_RESOURCE_NAME)
    raw = resource.read_bytes()
    if hashlib.sha256(raw).hexdigest() != LEDGER_FILE_SHA256:
        raise LegacyFftNativeWave45Error("packaged wave-45 ledger file SHA changed")
    try:
        parsed = json.loads(raw)
    except json.JSONDecodeError as exc:
        raise LegacyFftNativeWave45Error("packaged wave-45 ledger is invalid JSON") from exc
    if not isinstance(parsed, dict):
        raise LegacyFftNativeWave45Error("packaged wave-45 ledger must be an object")
    document = cast(dict[str, Any], parsed)
    claimed_content_sha256 = document.pop("ledger_content_sha256", None)
    if (
        claimed_content_sha256 != LEDGER_CONTENT_SHA256
        or hashlib.sha256(_canonical_bytes(document)).hexdigest() != LEDGER_CONTENT_SHA256
        or document.get("ledger_schema_version") != LEDGER_SCHEMA_VERSION
        or document.get("frozen_source_commit") != FROZEN_SOURCE_COMMIT
        or document.get("dataset_sha256") != PINNED_DATASET_SHA256
        or document.get("source_reference_runtime") != SOURCE_REFERENCE_RUNTIME
        or document.get("context_draw_count") != CONTEXT_DRAW_COUNT
        or document.get("minimum_history_by_method")
        != dict(MINIMUM_HISTORY_BY_SOURCE_NATIVE_WAVE45_METHOD)
        or document.get("source_sha256_by_method")
        != dict(SOURCE_SHA256_BY_SOURCE_NATIVE_WAVE45_METHOD)
    ):
        raise LegacyFftNativeWave45Error("packaged wave-45 ledger identity changed")
    targets_raw = document.get("target_draw_numbers")
    contexts_raw = document.get("context_numbers_sha256_by_target")
    tickets_raw = document.get("tickets_by_method")
    if (
        not isinstance(targets_raw, list)
        or not isinstance(contexts_raw, list)
        or not isinstance(tickets_raw, dict)
    ):
        raise LegacyFftNativeWave45Error("packaged wave-45 ledger layout changed")
    targets = cast(list[object], targets_raw)
    contexts = cast(list[object], contexts_raw)
    if (
        len(targets) != 1999
        or len(contexts) != 1999
        or len(set(targets)) != 1999
        or any(type(item) is not str or not item for item in targets)
        or any(
            type(item) is not str
            or len(item) != 64
            or any(character not in "0123456789abcdef" for character in item)
            for item in contexts
        )
    ):
        raise LegacyFftNativeWave45Error("packaged wave-45 target sequence changed")
    by_method: dict[str, tuple[tuple[Ticket, ...] | None, ...]] = {}
    typed_tickets = cast(dict[str, object], tickets_raw)
    if set(typed_tickets) != set(AUDITED_SOURCE_NATIVE_WAVE45_METHODS):
        raise LegacyFftNativeWave45Error("packaged wave-45 method set changed")
    for method_id in AUDITED_SOURCE_NATIVE_WAVE45_METHODS:
        raw_sequence = typed_tickets[method_id]
        if not isinstance(raw_sequence, list):
            raise LegacyFftNativeWave45Error("packaged wave-45 method sequence changed")
        sequence: list[tuple[Ticket, ...] | None] = []
        for candidate in cast(list[object], raw_sequence):
            if candidate is None:
                sequence.append(None)
                continue
            if not isinstance(candidate, list):
                raise LegacyFftNativeWave45Error("packaged wave-45 portfolio changed")
            portfolio = tuple(_ticket(ticket) for ticket in cast(list[object], candidate))
            if len(portfolio) != NATIVE_TICKET_COUNT_BY_SOURCE_NATIVE_WAVE45_METHOD[method_id]:
                raise LegacyFftNativeWave45Error("packaged wave-45 native ticket count changed")
            sequence.append(portfolio)
        if len(sequence) != len(targets):
            raise LegacyFftNativeWave45Error("packaged wave-45 target alignment changed")
        by_method[method_id] = tuple(sequence)
    return _Ledger(
        targets=cast(tuple[str, ...], tuple(targets)),
        context_sha256=cast(tuple[str, ...], tuple(contexts)),
        tickets_by_method=MappingProxyType(by_method),
    )


def load_legacy_fft_native_wave45_ledger_for_verification() -> _Ledger:
    """Expose the immutable checksummed ledger to contract tests."""

    return _load_ledger()


def _validate_request(request: LegacyFftNativeWave45Request) -> None:
    if request.legacy_method_id not in SUPPORTED_SOURCE_NATIVE_WAVE45_METHODS:
        raise LegacyFftNativeWave45Error("legacy method is outside the executable wave-45 batch")
    if (
        type(request.target_draw_number) is not str
        or not request.target_draw_number
        or request.dataset_sha256 != PINNED_DATASET_SHA256
        or type(request.replicate_id) is not int
        or request.replicate_id < 0
        or type(request.user_seed) not in (str, int)
    ):
        raise LegacyFftNativeWave45Error("invalid frozen FFT request identity")
    minimum = MINIMUM_HISTORY_BY_SOURCE_NATIVE_WAVE45_METHOD[request.legacy_method_id]
    if len(request.history) < minimum:
        raise LegacyFftNativeWave45SourceError("AVAILABLE_HISTORY_BELOW_FROZEN_SOURCE_MINIMUM")
    seen: set[str] = set()
    for draw in request.history:
        if (
            not draw.draw_number
            or draw.draw_number == request.target_draw_number
            or draw.draw_number in seen
        ):
            raise LegacyFftNativeWave45Error("causal history draw identities are invalid")
        _ticket(list(draw.numbers))
        seen.add(draw.draw_number)


def _context_sha256(history: tuple[LegacyHistoryDraw, ...]) -> str:
    context = [list(draw.numbers) for draw in history[-CONTEXT_DRAW_COUNT:]]
    return hashlib.sha256(json.dumps(context, separators=(",", ":")).encode("utf-8")).hexdigest()


def generate_legacy_fft_native_wave45_portfolio(
    request: LegacyFftNativeWave45Request,
) -> LegacyFftNativeWave45Result:
    """Return the exact positional portfolio for one causal target."""

    _validate_request(request)
    ledger = _load_ledger()
    try:
        target_index = ledger.targets.index(request.target_draw_number)
    except ValueError as exc:
        raise LegacyFftNativeWave45SourceError("TARGET_OUTSIDE_FROZEN_FFT_TICKET_LEDGER") from exc
    context_sha256 = _context_sha256(request.history)
    if context_sha256 != ledger.context_sha256[target_index]:
        raise LegacyFftNativeWave45SourceError("FROZEN_SOURCE_CONTEXT_IDENTITY_MISMATCH")
    tickets = ledger.tickets_by_method[request.legacy_method_id][target_index]
    if tickets is None:
        raise LegacyFftNativeWave45SourceError("AVAILABLE_HISTORY_BELOW_FROZEN_SOURCE_MINIMUM")
    seed_material = "|".join(
        (
            SOURCE_NATIVE_WAVE45_PROTOCOL,
            request.legacy_method_id,
            SOURCE_SHA256_BY_SOURCE_NATIVE_WAVE45_METHOD[request.legacy_method_id],
            request.target_draw_number,
            str(request.replicate_id),
            str(request.user_seed),
        )
    )
    seed_digest = hashlib.sha256(seed_material.encode("utf-8")).hexdigest()
    method_id = request.legacy_method_id
    return LegacyFftNativeWave45Result(
        tickets=tickets,
        metadata=LegacyFftNativeWave45Metadata(
            protocol=SOURCE_NATIVE_WAVE45_PROTOCOL,
            legacy_method_id=method_id,
            source_sha256=(SOURCE_SHA256_BY_SOURCE_NATIVE_WAVE45_METHOD[method_id]),
            target_draw_number=request.target_draw_number,
            replicate_id=request.replicate_id,
            user_seed=request.user_seed,
            seed_material=seed_material,
            seed_digest=seed_digest,
            seed_integer=int(seed_digest, 16),
            random_protocol="NONE_DETERMINISTIC_FROZEN_SOURCE",
            randomness_used=False,
            randomness_reproduction="NOT_APPLICABLE",
            history_draw_count=len(request.history),
            history_first_draw_number=request.history[0].draw_number,
            history_cutoff_draw_number=request.history[-1].draw_number,
            source_history_order="OLDEST_FIRST",
            source_history_order_detail=(
                "DATABASE_NEWEST_FIRST_REVERSED_ONCE_THEN_STRICT_PREFIX_"
                "BEFORE_TARGET_WITH_TRAILING_500_MAXIMUM_SOURCE_CONTEXT"
            ),
            source_minimum_history_draws=(
                MINIMUM_HISTORY_BY_SOURCE_NATIVE_WAVE45_METHOD[method_id]
            ),
            context_draw_count=min(
                len(request.history),
                CONTEXT_DRAW_COUNT,
            ),
            context_numbers_sha256=context_sha256,
            candidate_k=None,
            source_candidate_k_values=(MODEL_CANDIDATE_K,),
            native_ticket_count=len(tickets),
            native_ticket_count_semantics=(
                NATIVE_TICKET_SEMANTICS_BY_SOURCE_NATIVE_WAVE45_METHOD[method_id]
            ),
            native_ticket_order=("FROZEN_SOURCE_CONFIGURATION_THEN_POSITIONAL_BET_ORDER"),
            native_duplicate_ticket_count=len(tickets) - len(set(tickets)),
            combination_count=None,
            source_method_combination_count=(
                SOURCE_COMBINATION_COUNT_BY_SOURCE_NATIVE_WAVE45_METHOD[method_id]
            ),
            combination_members=(
                SOURCE_COMBINATION_MEMBERS_BY_SOURCE_NATIVE_WAVE45_METHOD[method_id]
            ),
            intra_ticket_order_semantics=(
                INTRA_TICKET_ORDER_SEMANTICS_BY_SOURCE_NATIVE_WAVE45_METHOD[method_id]
            ),
            source_reference_runtime=SOURCE_REFERENCE_RUNTIME,
            ledger_schema_version=LEDGER_SCHEMA_VERSION,
            ledger_file_sha256=LEDGER_FILE_SHA256,
            ledger_content_sha256=LEDGER_CONTENT_SHA256,
            ledger_target_index=target_index,
        ),
    )


