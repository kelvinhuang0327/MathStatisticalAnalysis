class LegacyFftNativeWave45Error(ValueError):
    """The request or packaged source-runtime ledger is invalid."""


class LegacyFftNativeWave45SourceError(LegacyFftNativeWave45Error):
    """A target cannot produce a source-valid wave-45 portfolio."""

    def __init__(self, reason_code: str) -> None:
        super().__init__(reason_code)
        self.reason_code = reason_code


