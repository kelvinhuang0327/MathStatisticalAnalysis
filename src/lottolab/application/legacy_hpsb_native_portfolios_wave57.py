class LegacyHpsbNativeWave57Error(ValueError):
    """The request or packaged ticket ledger violates the wave-57 contract."""


class LegacyHpsbNativeWave57SourceError(LegacyHpsbNativeWave57Error):
    """A target cannot safely consume its frozen native ticket."""

    def __init__(self, reason_code: str) -> None:
        super().__init__(reason_code)
        self.reason_code = reason_code


