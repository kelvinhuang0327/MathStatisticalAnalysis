@dataclass(frozen=True, slots=True)
class LegacyHpsbNativeWave57Result:
    tickets: tuple[Ticket, ...]
    metadata: LegacyHpsbNativeWave57Metadata


@dataclass(frozen=True, slots=True)
class _Ledger:
    targets: tuple[str, ...]
    context_sha256: tuple[str, ...]
    tickets_by_method: MappingProxyType[str, tuple[tuple[Ticket, ...], ...]]


def _canonical_bytes(value: object) -> bytes:
    return json.dumps(
        value,
        ensure_ascii=False,
        separators=(",", ":"),
        sort_keys=True,
    ).encode("utf-8")


def _ticket(value: object) -> Ticket:
    if not isinstance(value, list):
        raise LegacyHpsbNativeWave57Error(
            "packaged wave-57 ticket must be an array"
        )
    values = cast(list[object], value)
    integers = (
        cast(list[int], values)
        if all(type(number) is int for number in values)
        else []
    )
    if (
        len(integers) != 6
        or integers != sorted(integers)
        or len(set(integers)) != 6
        or any(not 1 <= number <= 49 for number in integers)
    ):
        raise LegacyHpsbNativeWave57Error(
            "packaged wave-57 ticket is not a sorted legal ticket"
        )
    return cast(Ticket, tuple(integers))


@lru_cache(maxsize=1)
def _load_ledger() -> _Ledger:
    resource = files("lottolab.strategies.data").joinpath(
        LEDGER_RESOURCE_NAME
    )
    raw = resource.read_bytes()
    if hashlib.sha256(raw).hexdigest() != LEDGER_FILE_SHA256:
        raise LegacyHpsbNativeWave57Error(
            "packaged wave-57 ledger file SHA changed"
        )
    try:
        parsed = json.loads(raw)
    except json.JSONDecodeError as exc:
        raise LegacyHpsbNativeWave57Error(
            "packaged wave-57 ledger is invalid JSON"
        ) from exc
    if not isinstance(parsed, dict):
        raise LegacyHpsbNativeWave57Error(
            "packaged wave-57 ledger must be an object"
        )
    document = cast(dict[str, Any], parsed)
    claimed_content_sha256 = document.pop("ledger_content_sha256", None)
    expected_source_hashes = {
        method_id: SOURCE_SHA256_BY_SOURCE_NATIVE_WAVE57_METHOD[method_id]
        for method_id in SUPPORTED_SOURCE_NATIVE_WAVE57_METHODS
    }
    expected_native_counts = {
        method_id: NATIVE_TICKET_COUNT_BY_SOURCE_NATIVE_WAVE57_METHOD[
            method_id
        ]
        for method_id in SUPPORTED_SOURCE_NATIVE_WAVE57_METHODS
    }
    if (
        claimed_content_sha256 != LEDGER_CONTENT_SHA256
        or hashlib.sha256(_canonical_bytes(document)).hexdigest()
        != LEDGER_CONTENT_SHA256
        or document.get("ledger_schema_version")
        != LEDGER_SCHEMA_VERSION
        or document.get("frozen_source_commit") != FROZEN_SOURCE_COMMIT
        or document.get("dataset_sha256") != PINNED_DATASET_SHA256
        or document.get("causal_eligibility_rule")
        != CAUSAL_ELIGIBILITY_RULE
        or document.get("context_policy") != CONTEXT_POLICY
        or document.get("native_ticket_count_by_method")
        != expected_native_counts
        or document.get("source_sha256_by_method")
        != expected_source_hashes
    ):
        raise LegacyHpsbNativeWave57Error(
            "packaged wave-57 ledger identity changed"
        )
    targets_raw = document.get("target_draw_numbers")
    contexts_raw = document.get("context_numbers_sha256_by_target")
    tickets_raw = document.get("tickets_by_method")
    if (
        not isinstance(targets_raw, list)
        or not isinstance(contexts_raw, list)
        or not isinstance(tickets_raw, dict)
    ):
        raise LegacyHpsbNativeWave57Error(
            "packaged wave-57 ledger layout changed"
        )
    targets = cast(list[object], targets_raw)
    contexts = cast(list[object], contexts_raw)
    if (
        len(targets) != 2149
        or len(contexts) != 2149
        or len(set(targets)) != 2149
        or any(type(item) is not str or not item for item in targets)
        or any(
            type(item) is not str
            or len(item) != 64
            or any(character not in "0123456789abcdef" for character in item)
            for item in contexts
        )
    ):
        raise LegacyHpsbNativeWave57Error(
            "packaged wave-57 target ledger changed"
        )
    typed_tickets = cast(dict[str, object], tickets_raw)
    if set(typed_tickets) != set(SUPPORTED_SOURCE_NATIVE_WAVE57_METHODS):
        raise LegacyHpsbNativeWave57Error(
            "packaged wave-57 method set changed"
        )
    by_method: dict[str, tuple[tuple[Ticket, ...], ...]] = {}
    for method_id in SUPPORTED_SOURCE_NATIVE_WAVE57_METHODS:
        rows_raw = typed_tickets[method_id]
        if not isinstance(rows_raw, list):
            raise LegacyHpsbNativeWave57Error(
                "packaged wave-57 ticket sequence changed"
            )
        rows: list[tuple[Ticket, ...]] = []
        for candidate in cast(list[object], rows_raw):
            if not isinstance(candidate, list):
                raise LegacyHpsbNativeWave57Error(
                    "packaged wave-57 portfolio changed"
                )
            portfolio = tuple(
                _ticket(ticket)
                for ticket in cast(list[object], candidate)
            )
            if len(portfolio) != 1:
                raise LegacyHpsbNativeWave57Error(
                    "packaged wave-57 native ticket count changed"
                )
            rows.append(portfolio)
        if len(rows) != len(targets):
            raise LegacyHpsbNativeWave57Error(
                "packaged wave-57 method target count changed"
            )
        by_method[method_id] = tuple(rows)
    return _Ledger(
        targets=cast(tuple[str, ...], tuple(targets)),
        context_sha256=cast(tuple[str, ...], tuple(contexts)),
        tickets_by_method=MappingProxyType(by_method),
    )


def load_legacy_hpsb_native_wave57_ledger_for_verification() -> _Ledger:
    """Expose the immutable checksummed ledger to verification code."""

    return _load_ledger()


def _validate_request(request: LegacyHpsbNativeWave57Request) -> None:
    if request.legacy_method_id not in SUPPORTED_SOURCE_NATIVE_WAVE57_METHODS:
        raise LegacyHpsbNativeWave57Error(
            "legacy method is outside the executable wave-57 batch"
        )
    if (
        type(request.target_draw_number) is not str
        or not request.target_draw_number
        or type(request.target_draw_date) is not date
        or type(request.replicate_id) is not int
        or request.replicate_id < 0
        or type(request.user_seed) not in (str, int)
        or type(request.dataset_sha256) is not str or not request.dataset_sha256
    ):
        raise LegacyHpsbNativeWave57Error(
            "invalid frozen HPSB request identity"
        )
    seen: set[str] = set()
    for draw in request.history:
        if (
            not draw.draw_number
            or draw.draw_number == request.target_draw_number
            or draw.draw_number in seen
        ):
            raise LegacyHpsbNativeWave57Error(
                "causal history draw identities are invalid"
            )
        _ticket(list(draw.numbers))
        seen.add(draw.draw_number)


def _full_context_sha256(
    history: tuple[LegacyHistoryDraw, ...],
) -> str:
    return hashlib.sha256(
        json.dumps(
            [list(draw.numbers) for draw in history],
            separators=(",", ":"),
        ).encode("utf-8")
    ).hexdigest()


def generate_legacy_hpsb_native_wave57_portfolio(
    request: LegacyHpsbNativeWave57Request,
) -> LegacyHpsbNativeWave57Result:
    """Return one exact frozen-runtime HPSB-V2 ticket."""

    _validate_request(request)
    ledger = _load_ledger()
    try:
        target_index = ledger.targets.index(request.target_draw_number)
    except ValueError as exc:
        raise LegacyHpsbNativeWave57SourceError(
            "TARGET_OUTSIDE_FROZEN_HPSB_TICKET_LEDGER"
        ) from exc
    context_sha256 = _full_context_sha256(request.history)
    if context_sha256 != ledger.context_sha256[target_index]:
        raise LegacyHpsbNativeWave57SourceError(
            "FROZEN_HPSB_FULL_PREFIX_CONTEXT_MISMATCH"
        )
    seed_material = f"random.seed({len(request.history)})"
    seed_digest = hashlib.sha256(
        seed_material.encode("utf-8")
    ).hexdigest()
    tickets = ledger.tickets_by_method[request.legacy_method_id][target_index]
    return LegacyHpsbNativeWave57Result(
        tickets=tickets,
        metadata=LegacyHpsbNativeWave57Metadata(
            protocol=SOURCE_NATIVE_WAVE57_PROTOCOL,
            legacy_method_id=request.legacy_method_id,
            source_sha256=SOURCE_SHA256_BY_SOURCE_NATIVE_WAVE57_METHOD[
                request.legacy_method_id
            ],
            target_draw_number=request.target_draw_number,
            target_draw_date=request.target_draw_date.isoformat(),
            replicate_id=request.replicate_id,
            user_seed=request.user_seed,
            seed_material=seed_material,
            seed_digest=seed_digest,
            seed_integer=len(request.history),
            random_protocol=RANDOM_PROTOCOL_BY_SOURCE_NATIVE_WAVE57_METHOD[
                request.legacy_method_id
            ],
            randomness_used=RANDOMNESS_USED_BY_SOURCE_NATIVE_WAVE57_METHOD[
                request.legacy_method_id
            ],
            randomness_reproduction=(
                "SOURCE_RUNTIME_LEDGER_EXACT_TICKET_REPLAY"
            ),
            history_draw_count=len(request.history),
            history_first_draw_number=(
                request.history[0].draw_number if request.history else None
            ),
            history_cutoff_draw_number=(
                request.history[-1].draw_number if request.history else None
            ),
            source_history_order="OLDEST_FIRST",
            source_history_order_detail=(
                "DATABASE_OLDEST_FIRST_FULL_STRICT_PREFIX_BEFORE_TARGET"
            ),
            context_draw_count=len(request.history),
            context_numbers_sha256=context_sha256,
            source_candidate_k_values=(
                SOURCE_CANDIDATE_K_VALUES_BY_SOURCE_NATIVE_WAVE57_METHOD[
                    request.legacy_method_id
                ]
            ),
            candidate_k=None,
            native_ticket_count=len(tickets),
            native_ticket_count_semantics=(
                NATIVE_TICKET_SEMANTICS_BY_SOURCE_NATIVE_WAVE57_METHOD[
                    request.legacy_method_id
                ]
            ),
            native_ticket_order=(
                "FROZEN_SOURCE_SINGLE_POSITION_BEFORE_ORDERED_20"
            ),
            native_duplicate_ticket_count=0,
            combination_count=None,
            local_source_configuration=(
                LOCAL_SOURCE_CONFIGURATION_BY_SOURCE_NATIVE_WAVE57_METHOD[
                    request.legacy_method_id
                ]
            ),
            imported_comparators_excluded=(
                IMPORTED_COMPARATORS_EXCLUDED_BY_SOURCE_NATIVE_WAVE57_METHOD[
                    request.legacy_method_id
                ]
            ),
            causal_eligibility_rule=CAUSAL_ELIGIBILITY_RULE,
            source_reference_runtime=SOURCE_REFERENCE_RUNTIME,
            ledger_schema_version=LEDGER_SCHEMA_VERSION,
            ledger_file_sha256=LEDGER_FILE_SHA256,
            ledger_content_sha256=LEDGER_CONTENT_SHA256,
            ledger_target_index=target_index,
            frozen_support_artifacts=(
                FROZEN_SUPPORT_ARTIFACTS_BY_SOURCE_NATIVE_WAVE57_METHOD[
                    request.legacy_method_id
                ]
            ),
        ),
    )


