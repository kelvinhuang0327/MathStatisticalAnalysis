def check_state(sigma: Sequence[int], zeta: Sequence[int]) -> None:
    require(len(sigma) == 14 and len(zeta) == 6, "cross-degree dimensions")
    require(
        all(type(s) is int and 0 <= s <= 6 - d for d, s in zip(CORE, sigma, strict=True)),
        "core pair capacity",
    )
    require(all(type(v) is int and 1 <= v <= 6 for v in zeta), "zero degree capacity")
    require(sum(sigma) == sum(zeta), "cross-edge balance")
    require(sum(sigma) % 2 == 0, "within-part edge parity")


def objective(sigma: Sequence[int], zeta: Sequence[int]) -> int:
    return (
        236
        + sum(s * (s - d - 4) for d, s in zip(CORE, sigma, strict=True))
        + sum(v * v for v in zeta)
    )


def triangle_from_state(sigma: Sequence[int], zeta: Sequence[int], remainder: int) -> int:
    check_state(sigma, zeta)
    require(type(remainder) is int and remainder >= 0, "negative remainder")
    return objective(sigma, zeta) - remainder


def relaxation_states() -> Iterator[State]:
    """Every class-sorted vector, without any unproved support/graph filters."""
    zero_by_sum: dict[int, list[tuple[int, ...]]] = defaultdict(list)
    for zeta in combinations_with_replacement(range(1, 7), 6):
        if sum(zeta) % 2 == 0:
            zero_by_sum[sum(zeta)].append(zeta)
    for five, four, three in product(
        combinations_with_replacement(range(2), 8),
        combinations_with_replacement(range(3), 2),
        combinations_with_replacement(range(4), 2),
    ):
        sigma = (0, 0, *five, *four, *three)
        for zeta in zero_by_sum[sum(sigma)]:
            yield sigma, zeta


